#!/usr/bin/env python3
"""Every VECTOR glyph species' table (prototype/vector/glyphs_*_vector.js), checked mechanically.

  shape      exactly 8 variants (the hardcoded % 8 in app/stage.html and app/settings.js), unique non-empty names
  loops      every glyph has >= 1 loop at both levels of detail (`loops`, `lo`); every loop has >= 3 distinct points
             and is CLOSED (the engine joins last to first: a loop whose last point repeats the first is refused,
             since that is a zero-length segment the native renderer would draw as a dot)
  unit box   every point lies in -1..1 on both axes, and the glyph reaches |x| or |y| >= 0.95 (so its size is its
             memory, not an accident of how much margin the source art had)
  symmetry   the point SET of each level is its own mirror about x = 0 (every (x, y) has a (-x, y) partner, to 1e-4):
             the owner's roster is all bilaterally symmetric, and the engine's mirror-symmetric CPU sweep relies on it
  partial    the five 2026-11-07 species (8 glyphs each, reach >= 0.90: drawn with margin); Made Marks also checks its dot lattices
  names      the vector table's names equal the Settings fallback NAMES for its species (app/settings.js)

Pure text parsing, no browser and no node. Exit 0 = pass. Add a species by adding its file to SPECIES below.
"""
import json, re, sys
from pathlib import Path

SPR = Path(__file__).resolve().parents[1]
SPECIES = [("c6_night", SPR / "prototype/vector/glyphs_night_vector.js")]
# The five 2026-11-07 species (owner's species ruling), generated by tools/species_glyph_sources.py. Made Marks is dots style and also carries lattices.
PARTIAL = [(c, SPR / f"prototype/vector/glyphs_{f}_vector.js") for c, f in [
    ("c7_patches", "mission_patches"), ("c8_instruments", "instrument_marks"), ("c9_wild", "wild_signs"),
    ("c10_made", "made_marks"), ("c11_old", "old_signs")]]
PARTIAL_N = 8
PARTIAL_IDS = {c for c, _ in PARTIAL}   # drawn with a little margin (0.90-0.99) in the 2048 px sources, kept so the dot lattices stay in register
DOTS = {"c10_made"}
_fails = []


def check(ok, msg):
    print(("PASS " if ok else "FAIL ") + msg, flush=True)
    if not ok: _fails.append(msg)
    return bool(ok)


def table(path):
    src = path.read_text()
    m = re.search(r"this\.SPRITES_GLYPHS_\w+_VECTOR\s*=\s*(\[[\s\S]*?\n\]);", src)
    if not m: raise SystemExit(f"{path}: no 'this.SPRITES_GLYPHS_*_VECTOR = [...];' found")
    return json.loads(m.group(1))


def settings_names(species):
    s = (SPR / "app/settings.js").read_text()
    m = re.search(species + r':\s*(\[[^\]]*\])', s)
    return json.loads(m.group(1)) if m else None


def main():
    n_glyphs = 0
    for species, path in SPECIES + PARTIAL:
        want = PARTIAL_N if (species, path) in PARTIAL else 8
        if not check(path.exists(), f"{species}: {path} exists"): continue
        t = table(path)
        check(len(t) == want, f"{species}: exactly {want} variants -- got {len(t)}")
        names = [e[0] for e in t]
        check(len(set(names)) == len(names) and all(isinstance(n, str) and n.strip() for n in names), f"{species}: unique non-empty names {names}")
        sn = settings_names(species)
        check((sn == names) if want == 8 else (sn is not None and sn[:len(names)] == names), f"{species}: names match app/settings.js NAMES fallback ({sn})")
        for name, g in t:
            n_glyphs += 1
            if species in DOTS:
                ok = set(g.get("dots", {})) == {"23", "64", "256"} and all(
                    len(d["p"]) % 3 == 0 and len(d["p"]) > 0 and d["d"] >= 1 and set(d["p"][2::3]) <= {0, 1} for d in g["dots"].values())
                check(ok, f"{species}/{name}: dot lattices at 23/64/256 well-formed")
                for E_, d in g["dots"].items():
                    pts = {(d["p"][i], d["p"][i + 1]) for i in range(0, len(d["p"]), 3)}
                    check(all((-x, y) in pts for x, y in pts), f"{species}/{name}/dots{E_}: lattice mirror-symmetric")
            for lvl in ("loops", "lo"):
                L = g.get(lvl) or []
                check(len(L) >= 1, f"{species}/{name}/{lvl}: at least one loop ({len(L)})")
                pts = [tuple(p) for l in L for p in l]
                closed = all(len({tuple(p) for p in l}) >= 3 and tuple(l[0]) != tuple(l[-1]) for l in L)
                check(closed, f"{species}/{name}/{lvl}: every loop has >= 3 distinct points and no repeated closing point")
                inbox = all(-1.0005 <= x <= 1.0005 and -1.0005 <= y <= 1.0005 for x, y in pts)
                reach = max(max(abs(x), abs(y)) for x, y in pts) if pts else 0
                check(inbox and reach >= (0.90 if species in PARTIAL_IDS else 0.95), f"{species}/{name}/{lvl}: inside the unit box and reaching it (max |coord| {reach:.4f})")
                key = lambda x, y: (round(x * 1e4), round(y * 1e4))
                S = {key(x, y) for x, y in pts}
                missing = [p for p in pts if key(-p[0], p[1]) not in S]
                check(not missing, f"{species}/{name}/{lvl}: mirror-symmetric about x = 0 ({len(pts)} points, {len(missing)} without a partner)")
    print(f"\n{'ALL PASS' if not _fails else str(len(_fails)) + ' FAIL'} ({n_glyphs} vector glyphs over {len(SPECIES) + len(PARTIAL)} species)", flush=True)
    sys.exit(1 if _fails else 0)


if __name__ == "__main__":
    main()
